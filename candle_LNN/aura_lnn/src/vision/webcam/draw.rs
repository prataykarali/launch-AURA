#![allow(clippy::too_many_arguments)]

pub fn draw_rect(
    buffer: &mut [u32],
    w: usize,
    h: usize,
    x1: i32,
    y1: i32,
    x2: i32,
    y2: i32,
    thickness: i32,
    color: u32,
) {
    for t in 0..thickness {
        let y_t = y1 + t;
        if y_t >= 0 && y_t < h as i32 {
            for x in x1.max(0)..=x2.min(w as i32 - 1) {
                buffer[(y_t as usize) * w + (x as usize)] = color;
            }
        }
        let y_b = y2 - t;
        if y_b >= 0 && y_b < h as i32 {
            for x in x1.max(0)..=x2.min(w as i32 - 1) {
                buffer[(y_b as usize) * w + (x as usize)] = color;
            }
        }
        let x_l = x1 + t;
        if x_l >= 0 && x_l < w as i32 {
            for y in y1.max(0)..=y2.min(h as i32 - 1) {
                buffer[(y as usize) * w + (x_l as usize)] = color;
            }
        }
        let x_r = x2 - t;
        if x_r >= 0 && x_r < w as i32 {
            for y in y1.max(0)..=y2.min(h as i32 - 1) {
                buffer[(y as usize) * w + (x_r as usize)] = color;
            }
        }
    }
}

pub fn draw_rect_filled(
    buffer: &mut [u32],
    w: usize,
    h: usize,
    x1: i32,
    y1: i32,
    x2: i32,
    y2: i32,
    color: u32,
) {
    for y in y1.max(0)..=y2.min(h as i32 - 1) {
        for x in x1.max(0)..=x2.min(w as i32 - 1) {
            buffer[(y as usize) * w + (x as usize)] = color;
        }
    }
}

pub fn draw_char(buffer: &mut [u32], w: usize, h: usize, ch: char, x: i32, y: i32, color: u32) {
    let glyph = get_glyph(ch);
    for (row, bits) in glyph.iter().enumerate() {
        let bits = *bits;
        for col in 0..8 {
            if (bits & (1 << (7 - col))) != 0 {
                let px = x + col;
                let py = y + row as i32;
                if px >= 0 && px < w as i32 && py >= 0 && py < h as i32 {
                    buffer[(py as usize) * w + (px as usize)] = color;
                }
            }
        }
    }
}

pub fn draw_string(
    buffer: &mut [u32],
    w: usize,
    h: usize,
    s: &str,
    mut x: i32,
    y: i32,
    color: u32,
) {
    for c in s.chars() {
        draw_char(buffer, w, h, c, x, y, color);
        x += 8;
    }
}

